DEFAULT_WIPE = ('userdata', 'metadata')
STATIC_OS = frozenset(DEFAULT_OS_IMAGES) | {'vbmeta_system', 'vbmeta_vendor'}
MAX_DOWNLOAD_SIZE = '0xf900000'   # script/generate-release.sh for caiman

