"""Reads a caiman flash-all.sh against the official GrapheneOS script (rules 4, 5 and 6).

GrapheneOS writes the script in two forms, and this reader supports both:

- legacy: device/common/generate-factory-images-common.sh, sourced by
  script/generate-release.sh with caiman's settings (DISABLE_UART, DISABLE_FIPS,
  DISABLE_DPM, AVB_PKMD, BOOTLOADER and RADIO from android-info.txt, lowercased). The
  whole expected text is fixed by the bootloader version, the baseband version and the
  build number, so the script must equal it byte for byte.
- optimized: what "fastboot -S 0xf900000 optimize-factory-image" writes into the published
  install zip, through FlashCapturer in system/core/fastboot/fastboot.cpp. Everything up
  to "fastboot snapshot-update cancel" is fixed and must be equal byte for byte. The OS
  images that follow come from the image zip's fastboot-info.txt, so they are read as a
  fixed list of static images, the wipe erases and a numbered run of super splits.

The optimized OS image list and wipe erases are fixed in this file. They are NOT yet
confirmed by any real install zip; DEFAULT_OS_IMAGES explains where they come from. No
option changes them at run time. A script that differs is refused until a reviewed change
to this file records what the real one does.

flash-all.bat and script.txt are not read.
"""
